// Uses the existing ghost mesh-tools dependencies; preserves geometry and texture bytes.
import fs from 'node:fs/promises';
import path from 'node:path';
import crypto from 'node:crypto';
import {NodeIO} from '@gltf-transform/core';
import {weld,dedup,prune} from '@gltf-transform/functions';
const file=process.argv[2]??'public/assets/models/environments/haunted-house/haunted-house.glb';
const dir=path.dirname(file),io=new NodeIO(),document=await io.read(file);
const primitives=()=>document.getRoot().listMeshes().flatMap(m=>m.listPrimitives());
const vertexCount=()=>primitives().reduce((s,p)=>s+p.getAttribute('POSITION').getCount(),0);
const hash=bytes=>crypto.createHash('sha256').update(bytes).digest('hex');
const textures=document.getRoot().listTextures().map(t=>hash(t.getImage())).sort();
const before={bytes:(await fs.stat(file)).size,vertices:vertexCount()};
const backup=path.resolve('.cache/3d-generation/runs/haunted-house/final-before-weld.glb');
await fs.mkdir(path.dirname(backup),{recursive:true});await fs.copyFile(file,backup);
await document.transform(weld(),dedup(),prune());
const afterTextures=document.getRoot().listTextures().map(t=>hash(t.getImage())).sort();
if(JSON.stringify(textures)!==JSON.stringify(afterTextures))throw Error('Unexpected texture change');
await io.write(file,document);
const after={bytes:(await fs.stat(file)).size,vertices:vertexCount()};
const report={method:'Exact vertex weld; material/texture deduplication; prune unused resources; no simplification or texture re-encoding',before,after,textureBytesPreserved:true,shadowMaps:1,shadowMapPixels:512,activeLocalLights:6,maxTextureSize:512,roomMaterialBatches:true,inactiveFloorCulling:true};
await fs.writeFile(path.join(dir,'optimization-report.json'),JSON.stringify(report,null,2));
const metaPath=path.join(dir,'generation-info.json'),meta=JSON.parse(await fs.readFile(metaPath,'utf8'));
meta.sha256=hash(await fs.readFile(file));meta.stats.bytes=after.bytes;meta.stats.vertices=after.vertices;meta.optimization=report;
await fs.writeFile(metaPath,JSON.stringify(meta,null,2));
const manifestPath=path.join(dir,'house-manifest.json'),manifest=JSON.parse(await fs.readFile(manifestPath,'utf8'));
manifest.stats.bytes=after.bytes;manifest.stats.vertices=after.vertices;
await fs.writeFile(manifestPath,JSON.stringify(manifest,null,2));
console.log(JSON.stringify(report,null,2));
